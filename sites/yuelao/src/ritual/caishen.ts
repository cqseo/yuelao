export const caiStickByNo = (no: number) => CAI_STICKS.find((s) => s.no === no) ?? null;

/** 付費解籤時給伺服器的籤內容。 */
export function caiContext(no: number) {
  const s = caiStickByNo(no);
  if (!s) return null;
  return {
    no: s.no,
    grade: s.grade,
    poem: s.poem.join('\n'),
    plain: s.plain,
    career: s.career,
    wealth: s.wealth,
    advice: s.advice,
  };
}
