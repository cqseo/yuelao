const RANK = ['一', '二', '三', '四', '五', '六', '七', '八', '九', '十', '侍從', '騎士', '王后', '國王'];

export const TAROT: TarotCard[] = [
  ...MAJOR.map(([n, name, kw, up, rev]) => ({ img: n, name, kw, up, rev })),
  ...SUITS.flatMap((s) =>
    s.cards.map(([kw, up, rev], i) => ({
      img: `${s.key}_${String(i + 1).padStart(2, '0')}`,
      name: i === 0 ? `${s.name}王牌` : `${s.name}${RANK[i]}`,
      kw,
      up,
      rev,
    })),
  ),
];

/** 同一天問同一件事，抽到的永遠是同一組牌（含正逆位）。 */
export function drawTarot(question: string, sit: string, day: string): { card: TarotCard; rev: boolean }[] {
  let h = 2166136261;
  for (const ch of `tarot|${day}|${sit}|${question.replace(/\s+/g, '')}`) {
    h ^= ch.codePointAt(0) ?? 0;
    h = Math.imul(h, 16777619);
  }
  const rnd = () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return (h >>> 0) / 4294967296;
  };
  const pool = TAROT.slice();
  const out: { card: TarotCard; rev: boolean }[] = [];
  for (let k = 0; k < 3; k++) {
    const card = pool.splice(Math.floor(rnd() * pool.length), 1)[0] as TarotCard;
    out.push({ card, rev: rnd() < 0.3 });
  }
  return out;
}
