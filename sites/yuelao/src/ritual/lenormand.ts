// 三張的走勢：看第一張和第三張的傾向，以及中間那張是推還是擋。
export function flowLine(a: LenormandCard, b: LenormandCard, c: LenormandCard): string {
  const s = (t: Tone) => (t === 'good' ? 1 : t === 'hard' ? -1 : 0);
  const from = s(a.tone);
  const mid = s(b.tone);
  const to = s(c.tone);
  if (to > 0 && from < 0)
    return `從「${a.name}」的不順開始，經過「${b.name}」，最後落在「${c.name}」：先難後好。`;
  if (to > 0 && mid < 0)
    return `「${a.name}」起頭，中間卡在「${b.name}」，但最後是「${c.name}」：過了這關就好轉。`;
  if (to > 0) return `從「${a.name}」到「${c.name}」，一路往好的方向走，「${b.name}」是中間推了一把的力量。`;
  if (to < 0 && from > 0)
    return `「${a.name}」開了個好頭，經過「${b.name}」，卻走向「${c.name}」：要留意好的開頭沒能守住。`;
  if (to < 0 && mid < 0)
    return `「${b.name}」和「${c.name}」連在一起，這件事的壓力是真的；先照顧好自己，再決定要不要繼續用力。`;
  if (to < 0)
    return `走向是「${c.name}」，不算輕鬆；它說的是方向，不是判決，「${b.name}」那一步怎麼走還在你手上。`;
  if (mid > 0)
    return `結果落在「${c.name}」，還沒定型；中間的「${b.name}」是助力，順著它做，結果會偏向好的那一邊。`;
  if (mid < 0) return `結果落在「${c.name}」，還沒定型；中間的「${b.name}」在擋路，先處理它。`;
  return `「${a.name}」「${b.name}」「${c.name}」都要看組合：這件事還在成形，下一步你怎麼做，分量很重。`;
}

/** 同一天問同一件事，抽到的永遠是同一組牌。 */
export function drawThree(question: string, sit: string, day: string): LenormandCard[] {
  let h = 2166136261;
  for (const ch of `${day}|${sit}|${question.replace(/\s+/g, '')}`) {
    h ^= ch.codePointAt(0) ?? 0;
    h = Math.imul(h, 16777619);
  }
  const rnd = () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return (h >>> 0) / 4294967296;
  };
  const pool = LENORMAND.slice();
  const out: LenormandCard[] = [];
  for (let k = 0; k < 3; k++) out.push(pool.splice(Math.floor(rnd() * pool.length), 1)[0] as LenormandCard);
  return out;
}
